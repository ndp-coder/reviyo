// Prepare the reviewed sandbox diagnostic as one file for Supabase's editor.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import ts from 'typescript';
const read = path => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
const target = process.argv[2] ?? 'qikink-sandbox-check';
if (!['qikink-sandbox-check', 'qikink-live-check'].includes(target)) throw new Error('Unsupported diagnostic target.');
const source = await read('supabase/functions/_shared/autopay.ts');
const parsed = ts.createSourceFile('autopay.ts', source, ts.ScriptTarget.Latest, true);
const wanted = new Set(['getSupabaseSecretKey', 'createAdminClient']);
const helpers = parsed.statements.filter(node => ts.isFunctionDeclaration(node) && wanted.has(node.name?.text));
if (helpers.length !== 2) throw new Error('Expected the existing server key and client helpers.');
const client = await read('supabase/functions/_shared/qikink.ts');
const entry = await read(`supabase/functions/${target}/index.ts`);
const entryParsed = ts.createSourceFile('index.ts', entry, ts.ScriptTarget.Latest, true);
const entryBody = entryParsed.statements.filter(node => !ts.isImportDeclaration(node)).map(node => node.getText(entryParsed)).join('\n');
const bundle = `// Generated by scripts/bundle-qikink-sandbox-check.mjs for ${target}.\nimport type { SupabaseClient } from "npm:@supabase/supabase-js@2.57.4";\ntype AdminClient = SupabaseClient;\n${helpers.map(node => node.getText(parsed)).join('\n')}\n${client}\n${entryBody}\n`;
await mkdir(new URL('../output/', import.meta.url), { recursive: true });
await writeFile(new URL(`../output/${target}.bundle.ts`, import.meta.url), bundle);
console.log(`Prepared ${target} bundle.`);
